"""Write the material table of dbr-structures/dbr-engine.js from engines/materials (the Python reference).

The block between the `materials:begin` and `materials:end` markers is replaced; the evaluator matN() in
dbr-engine.js implements the same four dispersion forms. Run from math-engines/:  python tools/gen_js_materials.py
engines/test_js_materials_current.py fails when the block is out of date.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from engines.materials import engine as mat  # noqa: E402

TARGET = ROOT.parent / "dbr-structures" / "dbr-engine.js"
BEGIN, END = "/* materials:begin", "/* materials:end */"

# JS key: (Python key, label in the page)
KEYS = {
    "sio2": ("sio2", "SiO₂ (fused silica)"),
    "si3n4": ("si3n4", "Si₃N₄ (LPCVD)"),
    "lne": ("ln_e", "LiNbO₃ extraordinary (5% MgO, Zelmon)"),
    "lno": ("ln_o", "LiNbO₃ ordinary (5% MgO, Zelmon)"),
    "lneT": ("ln_e_gayer", "LiNbO₃ extraordinary (5% MgO, Gayer, temperature)"),
    "lte": ("lt_e_bond", "LiTaO₃ extraordinary (Bond refit)"),
    "lto": ("lt_o_bond", "LiTaO₃ ordinary (Bond refit)"),
    "si": ("si", "Si (real part only)"),
    "ktpx": ("ktp_x", "KTP n_x"),
    "ktpy": ("ktp_y", "KTP n_y"),
    "ktpz": ("ktp_z", "KTP n_z"),
    "bboo": ("bbo_o", "BBO ordinary"),
    "bboe": ("bbo_e", "BBO extraordinary"),
    "alno": ("aln_o", "AlN ordinary"),
    "alne": ("aln_e", "AlN extraordinary"),
    "gaas": ("gaas", "GaAs"),
    "tio2o": ("tio2_o", "TiO₂ rutile ordinary"),
    "tio2e": ("tio2_e", "TiO₂ rutile extraordinary"),
    "sapo": ("sapphire_o", "Sapphire ordinary"),
    "sape": ("sapphire_e", "Sapphire extraordinary"),
}


def entry(py):
    """Form and coefficients of one material, in µm as tabulated."""
    if py == "ln_e_gayer":
        g = mat._GAYER_E
        d = {"f": "g", "a": list(g["a"]), "b": list(g["b"]), "T0": g["T0"]}
    elif py in mat._POLES_SQ:
        c0, poles = mat._POLES_SQ[py]
        d = {"f": "p", "c0": c0, "poles": [list(p) for p in poles]}
    elif py in mat._FORM4:
        c, poles, poly = mat._FORM4[py]
        d = {"f": "4", "c": c, "poles": [list(p) for p in poles], "poly": [list(p) for p in poly]}
    else:
        d = {"f": "s", "terms": [list(t) for t in mat._SELLMEIER[py]]}
    rng = mat.VALID_RANGE.get(py)
    if rng:
        d["range"] = [rng[0] * 1e6, rng[1] * 1e6]
    return d


def block() -> str:
    lines = [f"{BEGIN} (generated by math-engines/tools/gen_js_materials.py from engines/materials; do not edit) */",
             "const MAT_DATA = {"]
    for js, (py, label) in KEYS.items():
        d = {"label": label, "py": py, **entry(py)}
        lines.append(f"  {js}: {json.dumps(d, ensure_ascii=False)},")
    lines.append("};")
    lines.append(END)
    return "\n".join(lines)


def render(src: str) -> str:
    a, b = src.index(BEGIN), src.index(END) + len(END)
    return src[:a] + block() + src[b:]


if __name__ == "__main__":
    TARGET.write_text(render(TARGET.read_text(encoding="utf-8")), encoding="utf-8")
    print(f"wrote the material block of {TARGET.relative_to(ROOT.parent)}", file=sys.stderr)
