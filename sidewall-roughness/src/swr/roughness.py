"""Random sidewall roughness fields h(x, z) and their spectra.

Conventions (used everywhere in the package, also by the spectral-probe analysis):

* Autocorrelation R(u) = <h(x) h(x + u)>, R(0) = sigma**2.
    gaussian:     R(u) = sigma**2 * exp(-u**2 / Lc**2)
    exponential:  R(u) = sigma**2 * exp(-|u| / Lc)
  so R(Lc) = sigma**2 / e for both kinds.
* Two-sided power spectral density S(K) = (1 / 2 pi) * integral R(u) exp(-i K u) du,
  normalised so that integral_{-inf}^{inf} S(K) dK = sigma**2.
    gaussian:     S(K) = sigma**2 * Lc / (2 sqrt(pi)) * exp(-K**2 Lc**2 / 4)
    exponential:  S(K) = sigma**2 * Lc / (pi * (1 + K**2 Lc**2))
* A 2D field h(x, z) has the separable ACF R(u, v) = sigma**2 * r_x(u / Lc) * r_z(v / Lz).
  Lz = None (or inf) is columnar roughness: h does not depend on z.

Fields are generated by spectral filtering of white noise on a periodic grid, so the
domain must be many correlation lengths long or the wrap-around correlation shows.
Lengths are in whatever unit the caller uses consistently (the package uses um).
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

ACF_KINDS = ("gaussian", "exponential")


@dataclass(frozen=True)
class RoughnessSpec:
    sigma: float
    lc: float
    lz: float | None = None
    acf: str = "gaussian"
    acf_z: str | None = None

    def __post_init__(self):
        if self.sigma < 0 or self.lc <= 0:
            raise ValueError("sigma must be >= 0 and lc > 0")
        if self.lz is not None and not np.isinf(self.lz) and self.lz <= 0:
            raise ValueError("lz must be positive, None or inf")
        for kind in (self.acf, self.acf_z or self.acf):
            if kind not in ACF_KINDS:
                raise ValueError(f"unknown acf {kind!r}; use one of {ACF_KINDS}")

    @property
    def columnar(self) -> bool:
        return self.lz is None or np.isinf(self.lz)


def acf_1d(u, sigma, lc, acf="gaussian"):
    u = np.abs(np.asarray(u, dtype=float))
    if acf == "gaussian":
        return sigma**2 * np.exp(-((u / lc) ** 2))
    if acf == "exponential":
        return sigma**2 * np.exp(-u / lc)
    raise ValueError(f"unknown acf {acf!r}")


def psd_1d(k, sigma, lc, acf="gaussian"):
    """Two-sided PSD S(K) with integral over all K equal to sigma**2."""
    k = np.asarray(k, dtype=float)
    if acf == "gaussian":
        return sigma**2 * lc / (2.0 * np.sqrt(np.pi)) * np.exp(-((k * lc) ** 2) / 4.0)
    if acf == "exponential":
        return sigma**2 * lc / (np.pi * (1.0 + (k * lc) ** 2))
    raise ValueError(f"unknown acf {acf!r}")


def _filter(n, d, lc, acf):
    """Amplitude filter a_m with a_m**2 = n * s(K_m) * dK for a unit-variance spectrum s."""
    k = 2.0 * np.pi * np.fft.fftfreq(n, d=d)
    dk = 2.0 * np.pi / (n * d)
    weights = psd_1d(k, 1.0, lc, acf) * dk
    weights /= weights.sum()
    return np.sqrt(n * weights)


def generate(spec: RoughnessSpec, nx: int, dx: float, nz: int = 1, dz: float | None = None,
             seed: int | None = None) -> np.ndarray:
    """One realization h[z_index, x_index] of shape (nz, nx), periodic in x (and z).

    The discrete spectrum is renormalised so that the expected variance is exactly
    sigma**2 on this grid; a single realization fluctuates around it.
    """
    rng = np.random.default_rng(seed)
    ax = _filter(nx, dx, spec.lc, spec.acf)
    if spec.columnar or nz == 1:
        white = rng.standard_normal(nx)
        row = np.real(np.fft.ifft(np.fft.fft(white) * ax)) * spec.sigma
        return np.broadcast_to(row, (nz, nx)).copy()
    if dz is None:
        raise ValueError("dz is required for a z-correlated (finite lz) field")
    az = _filter(nz, dz, spec.lz, spec.acf_z or spec.acf)
    white = rng.standard_normal((nz, nx))
    spectrum = np.fft.fft2(white) * az[:, None] * ax[None, :]
    return np.real(np.fft.ifft2(spectrum)) * spec.sigma


def measure_acf(h: np.ndarray, axis: int = -1) -> np.ndarray:
    """Periodic ACF estimate along `axis`, averaged over the other axes; index = lag in samples."""
    h = np.asarray(h, dtype=float)
    h = h - h.mean(axis=axis, keepdims=True)
    n = h.shape[axis]
    spec = np.abs(np.fft.fft(h, axis=axis)) ** 2
    acf = np.real(np.fft.ifft(spec, axis=axis)) / n
    acf = np.moveaxis(acf, axis, -1).reshape(-1, n)
    return acf.mean(axis=0)


def fit_correlation_length(acf: np.ndarray, d: float) -> float:
    """Lag where the ACF first drops below R(0)/e, linearly interpolated."""
    target = acf[0] / np.e
    below = np.nonzero(acf < target)[0]
    if below.size == 0:
        return np.inf
    i = below[0]
    frac = (acf[i - 1] - target) / (acf[i - 1] - acf[i])
    return (i - 1 + frac) * d


def sinusoid(x, amplitude: float, period: float, phase: float = 0.0) -> np.ndarray:
    """Spectral-probe corrugation h = A sin(2 pi x / Lambda + phase); its sigma**2 = A**2 / 2."""
    return amplitude * np.sin(2.0 * np.pi * np.asarray(x, dtype=float) / period + phase)
