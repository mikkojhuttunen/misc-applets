"""Build <applet>-standalone.html: an artifact page wrapped as a complete HTML document.

The artifact host adds <!doctype html>, <head> (charset, viewport) and a small reset when it publishes a page;
this script adds the same so the file opens directly in a browser, offline.
Run from the repository root:  python tools/build_standalone.py [applet.html ...]   (default: all applets below)
Complete documents with local scripts (DOCUMENTS) get the scripts inlined instead.
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APPLETS = {
    "cmpc-ray-tracer.html": ("CMPC Ray Tracer", "billiard_cell, ray_phase, bragg_grating (stack_R_oblique, TrenchDBR) and cell_mirror engines"),
    "fringe-washout.html": ("Fringe Washout Planner", "fringe_averaging engine"),
}
# complete documents that load local scripts: the scripts are inlined (output name, title, engines)
DOCUMENTS = {
    "dbr-structures/index.html": ("dbr-structures-standalone.html", "Waveguide DBR Calculator",
                                  "materials, slab_waveguide, bragg_grating, grating_coupler and crigf engines (dbr-engine.js)"),
}
SCRIPT_SRC = re.compile(r'<script src="([^"/:]+\.js)"></script>')


def _rev() -> str:
    try:
        return subprocess.check_output(["git", "rev-parse", "--short", "HEAD"], text=True, cwd=ROOT).strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def build_document(name: str) -> str:
    """Inline every local <script src> of a complete HTML document and add a provenance comment."""
    out_name, title, engines = DOCUMENTS[name]
    path = ROOT / name
    src = path.read_text(encoding="utf-8")

    def inline(m):
        js = (path.parent / m.group(1)).read_text(encoding="utf-8")
        assert "</script" not in js, f"{m.group(1)} contains </script>"
        return f"<script>/* {m.group(1)} (inlined) */\n{js}</script>"

    body = SCRIPT_SRC.sub(inline, src)
    note = f"""<!--
  {title}, standalone single-file build (generated by tools/build_standalone.py; edit {name} and its scripts).
  Source: github.com/mikkojhuttunen/misc-applets, {name} at commit {_rev()}.
  Physics: JS port of the misc-applets math-engines {engines},
  checked there against the Python reference by math-engines/tools/check_js_ports.mjs.
  No build step and no server needed: open the file in a browser. Google Fonts are optional (system fonts offline).
-->"""
    at = body.index(">", body.index("<meta charset")) + 1            # keep the charset declaration first
    return body[:at] + "\n" + note + body[at:]


def build(name="cmpc-ray-tracer.html") -> str:
    if name in DOCUMENTS:
        return build_document(name)
    title, engines = APPLETS[name]
    src = (ROOT / name).read_text(encoding="utf-8")
    rev = _rev()
    title_end = src.index("</title>") + len("</title>")
    rest = src[title_end:]
    style_end = rest.index("</style>") + len("</style>")
    return f'''<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<!--
  {title}, standalone single-file build (generated by tools/build_standalone.py; edit {name}).
  Source: github.com/mikkojhuttunen/misc-applets, {name} at commit {rev}.
  Physics: inline JS port (between the engine:begin / engine:end markers) of the misc-applets math-engines
  {engines}, checked there against the Python reference by math-engines/tools/check_js_ports.mjs.
  No build step and no server needed: open the file in a browser. Google Fonts are optional (system fonts offline).
  Heavy analyses run in Web Workers created from the inline engine (blob URLs).
-->
{src[:title_end]}
<style>
:root {{ color-scheme: light; }}
body {{ margin: 0; }}
img {{ max-width: 100%; }}
[hidden] {{ display: none !important; }}
</style>
{rest[:style_end]}
</head>
<body>
{rest[style_end:].strip()}
</body>
</html>
'''


def output_path(name: str) -> Path:
    return ROOT / (DOCUMENTS[name][0] if name in DOCUMENTS else name.replace(".html", "-standalone.html"))


if __name__ == "__main__":
    for name in sys.argv[1:] or [*APPLETS, *DOCUMENTS]:
        out = output_path(name)
        out.write_text(build(name), encoding="utf-8")
        print(f"wrote {out.name}")
